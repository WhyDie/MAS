// Track rate limiting to skip API calls when limited
let isRateLimited = false;
let rateLimitResetAt = 0;

interface AIResponse {
  success: boolean;
  message?: string;
  error?: string;
}

export async function chatWithAI(userMessage: string, maxRetries: number = 0): Promise<AIResponse> {
  const apiKey = process.env.OPENROUTER_API_KEY;

  // If API key is set, try real AI first (single attempt, no retries)
  if (apiKey && apiKey.length > 10) {
    // Check if we're currently rate limited
    const now = Date.now();
    if (isRateLimited && now < rateLimitResetAt) {
      console.log('[AI] ⏭️ Skipping API call (rate limited, resets at', new Date(rateLimitResetAt).toLocaleTimeString(), ')');
      return { success: true, message: getSmartResponse(userMessage) };
    }
    
    // Rate limit period expired, try again
    if (isRateLimited && now >= rateLimitResetAt) {
      console.log('[AI] 🔄 Rate limit period expired, trying API again...');
      isRateLimited = false;
    }
    
    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), OPENROUTER_API_TIMEOUT_MS);

      const response = await fetch(OPENROUTER_API_URL, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${apiKey}`,
          'HTTP-Referer': process.env.APP_URL || 'http://localhost:3000',
          'X-Title': 'Military Adaptation System',
        },
        body: JSON.stringify({
          model: 'nvidia/nemotron-nano-9b-v2:free',
          messages: [
            { role: 'system', content: SYSTEM_PROMPT },
            { role: 'user', content: userMessage },
          ],
          max_tokens: 1500,
          temperature: 0.7,
        }),
        signal: controller.signal,
      });

      clearTimeout(timeoutId);

      if (response.ok) {
        const data: any = await response.json();
        const aiMessage = data.choices?.[0]?.message?.content;
        if (aiMessage) {
          console.log('[AI] ✅ OpenRouter response');
          return { success: true, message: aiMessage };
        }
      } else if (response.status === 429) {
        // Rate limited - parse reset time and skip future calls
        const resetTime = parseInt(response.headers.get('X-RateLimit-Reset') || '0');
        if (resetTime > 0) {
          rateLimitResetAt = resetTime;
          isRateLimited = true;
          console.log('[AI] ⚠️ Rate limited until', new Date(rateLimitResetAt).toLocaleTimeString());
        } else {
          console.log('[AI] ⚠️ Rate limited (no reset time)');
        }
      } else {
        const errorText = await response.text();
        console.error(`[AI] ❌ Error ${response.status}:`, errorText);
      }
    } catch (error: any) {
      if (error.name === 'AbortError' || error.message?.includes('aborted')) {
        console.error(`[AI] ❌ Failed: OpenRouter request aborted after ${OPENROUTER_API_TIMEOUT_MS / 1000}s timeout.`);
      } else {
        console.error(`[AI] ❌ Failed:`, error.message);
      }
    }
  }

  // Local smart responses (instant, no API call needed)
  return {
    success: true,
    message: getSmartResponse(userMessage),
  };
}

