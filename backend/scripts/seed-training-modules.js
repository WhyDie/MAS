const stmt = db.prepare(`
  INSERT OR REPLACE INTO training_modules
  (id, title, description, category, durationMinutes, difficulty, content, isOfflineAvailable, tags, viewCount, createdAt, updatedAt)
  VALUES (?, ?, ?, ?, ?, ?, ?, 1, ?, 0, ?, ?)
`);

const insertMany = db.transaction((modules) => {
  let count = 0;
  for (const m of modules) {
    stmt.run(uuid(), m.title, m.description, m.category, m.durationMinutes, m.difficulty, JSON.stringify({ text: m.content || m.description }), m.tags ? JSON.stringify(m.tags) : '[]', now, now);
    count++;
    console.log(`  ✅ ${m.title}`);
  }
  return count;
});

try {
  const inserted = insertMany(modules);
  console.log(`\n✅ Successfully seeded ${inserted} training modules!`);
} catch (err) {
  console.error('❌ Error:', err.message);
}

db.close();
