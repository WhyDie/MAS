const stmt = db.prepare(`
  INSERT OR REPLACE INTO knowledge_base_articles
  (id, title, description, content, category, difficulty, tags, estimatedMinutes, viewCount, isPublished, authorId, createdAt, updatedAt)
  VALUES (@id, @title, @description, @content, @category, @difficulty, @tags, @estimatedMinutes, @viewCount, @isPublished, @authorId, @createdAt, @updatedAt)
`);

const insertMany = db.transaction((articles) => {
  let count = 0;
  for (const article of articles) {
    stmt.run({
      id: article.id,
      title: article.title,
      description: article.description,
      content: article.content,
      category: article.category,
      difficulty: article.difficulty,
      tags: JSON.stringify(article.tags),
      estimatedMinutes: article.estimatedMinutes,
      viewCount: 0,
      isPublished: article.isPublished ? 1 : 0,
      authorId: null,
      createdAt: new Date().toISOString().replace('T', ' ').substring(0, 19),
      updatedAt: new Date().toISOString().replace('T', ' ').substring(0, 19),
    });
    count++;
    console.log(`  ✅ ${article.title}`);
  }
  return count;
});

try {
  const inserted = insertMany(articles);
  console.log(`\n✅ Successfully seeded ${inserted} articles!`);
} catch (err) {
  console.error('❌ Error seeding articles:', err.message);
}

db.close();
